// Copies the free starter set (scripts/free-icons.json) out of Patine Pro's icons into src/, so the public package is
// plain committed files and nothing here imports Pro. Run it on a machine that has the private repo:
//   node scripts/icons.js [path/to/private/pro]   default: ../../private/pro from this package
// The glyph data is the same as Pro's, so every free icon is also a Pro icon under the same name.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const PACKAGE = path.join(__dirname, '..');
const REPO = path.join(PACKAGE, '..', '..');
const SRC = path.join(PACKAGE, 'src');
const GLYPHS = path.join(SRC, 'glyphs');
const MCP_ICONS = path.join(REPO, 'packages', 'mcp', 'src', 'icons.json');
const FREE = require('./free-icons.json');

const HEADER =
  "// Generated by packages/icons/scripts/icons.js from Patine Pro's icons. Do not edit: run `pnpm --filter @patine-ui/icons icons`.\n";
const exportName = (name) => `icon${name[0].toUpperCase()}${name.slice(1)}`;
const base = (icon) => icon.file.replace(/\.svg$/, '');

const main = () => {
  const pro = path.resolve(process.argv[2] ?? path.join(REPO, 'private', 'pro'));
  const { readIcons } = require(path.join(pro, 'scripts', 'icons.js'));
  const { icons: all, errors } = readIcons();
  if (errors.length) throw new Error(`Pro's icons have errors:\n${errors.join('\n')}`);
  const byName = new Map(all.map((icon) => [icon.glyph.name, icon]));
  const missing = FREE.filter((name) => !byName.has(name));
  if (missing.length) throw new Error(`Not in Pro: ${missing.join(', ')}`);
  const icons = [...FREE].sort().map((name) => byName.get(name));

  fs.rmSync(GLYPHS, { recursive: true, force: true });
  fs.mkdirSync(GLYPHS);
  for (const icon of icons)
    fs.writeFileSync(
      path.join(GLYPHS, `${base(icon)}.ts`),
      `${HEADER}import type { IconGlyph } from '../icons.types';\n\nexport const ${exportName(icon.glyph.name)}: IconGlyph = ${JSON.stringify(
        icon.glyph
      ).replace(/"(\w+)":/g, '$1:')};\n`
    );
  fs.writeFileSync(
    path.join(GLYPHS, 'index.ts'),
    `${HEADER}${icons.map((icon) => `export { ${exportName(icon.glyph.name)} } from './${base(icon)}';`).join('\n')}\n`
  );
  fs.writeFileSync(
    path.join(SRC, 'icons.registry.ts'),
    `${HEADER}import { ${icons.map((i) => exportName(i.glyph.name)).join(', ')} } from './glyphs';\n\n` +
      '/** Every free icon by name, for `<Icon name="…" />`. Importing this pulls in the whole set; import single glyphs to stay light. */\n' +
      `export const ICONS = { ${icons.map((i) => `${i.glyph.name}: ${exportName(i.glyph.name)}`).join(', ')} } as const;\n\n` +
      'export type IconName = keyof typeof ICONS;\n'
  );
  fs.writeFileSync(
    path.join(SRC, 'icons.meta.ts'),
    `${HEADER}import type { IconName } from './icons.registry';\n\n` +
      '/** Category and search words per icon, for galleries, icon pickers and search. */\n' +
      `export const ICON_META: Record<IconName, { category: string; tags: string }> = ${JSON.stringify(
        Object.fromEntries(icons.map((i) => [i.glyph.name, i.meta]))
      )};\n`
  );
  // The MCP server's `search_icons` reads the same list, so agents find the names that exist.
  const list = icons.map((i) => ({
    name: i.glyph.name,
    ...i.meta,
  }));
  fs.writeFileSync(MCP_ICONS, `${JSON.stringify(list)}\n`);
  execFileSync(
    path.join(REPO, 'node_modules', '.bin', 'biome'),
    ['check', '--write', GLYPHS, path.join(SRC, 'icons.registry.ts'), path.join(SRC, 'icons.meta.ts'), MCP_ICONS],
    {
      cwd: REPO,
      stdio: 'ignore',
    }
  );
  process.stdout.write(`${icons.length} free icons written.\n`);
};

main();
